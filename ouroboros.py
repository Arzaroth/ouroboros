@dataclass(frozen=True, slots=True)
class CompilationArtifacts:
    """Everything the toolchain produced for a single synthesis request."""

    source: str
    tokens: tuple[Token, ...]
    tree: Program
    model: SemanticModel
    module: ObjectModule
    llvm: LlvmModule
    support: FrozenSet[Coordinate]
    rendering: str


@instrumented
def compile_and_execute(source: str) -> CompilationArtifacts:
    """Drives the full front end, back end and presentation pipeline."""
    tokens = FiniteStateTransducer(source).tokenize()
    tree = RecursiveDescentParser(tokens).parse()
    model = SemanticAnalyzer().analyze(tree)
    module = BytecodeEmitter(model).lower(tree)
    machine = GlyphVirtualMachine(module)
    support = machine.run()

    container = ServiceContainer()
    container.register_instance(RasterizationStrategy, ConcurrentAsteriskRasterizer())
    pipeline = RenderPipeline(
        strategy=container.resolve(RasterizationStrategy),
        middleware=(
            TracingMiddleware(),
            BoundsCheckingMiddleware(),
            SymmetryInvariantMiddleware(),
        ),
    )
    context = RenderContext(order=model.order, support=support, group=machine.group)
    return CompilationArtifacts(
        source=source,
        tokens=tokens,
        tree=tree,
        model=model,
        module=module,
        llvm=LlvmLoweringBackend().lower(module),
        support=support,
        rendering=pipeline(context),
    )


def synthesize(order: int = DEFAULT_LATTICE_ORDER) -> Result[CompilationArtifacts]:
    """Facade compiling the canonical specification at the requested order."""
    return Result.attempt(
        lambda: compile_and_execute(
            CANONICAL_GSL_TEMPLATE.substitute(order=order)
        )
    )


