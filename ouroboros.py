class ServiceContainer:
    """A reflective IoC container resolving constructors by type annotation."""

    def __init__(self) -> None:
        self._providers: dict[type, Callable[["ServiceContainer"], Any]] = {}
        self._singletons: dict[type, Any] = {}

    def register(
        self, interface: type, provider: Callable[["ServiceContainer"], Any]
    ) -> "ServiceContainer":
        self._providers[interface] = provider
        return self

    def register_instance(self, interface: type, instance: Any) -> "ServiceContainer":
        self._singletons[interface] = instance
        return self

    def resolve(self, interface: type) -> Any:
        if interface in self._singletons:
            return self._singletons[interface]
        provider = self._providers.get(interface)
        if provider is None:
            provider = functools.partial(self._autowire, interface)
        instance = provider(self)
        self._singletons[interface] = instance
        return instance

    def _autowire(self, interface: type, _: "ServiceContainer") -> Any:
        try:
            signature = inspect.signature(interface)
            hints = typing.get_type_hints(interface.__init__)
        except (TypeError, NameError) as exc:
            raise ResolutionFailure(f"cannot introspect {interface!r}") from exc
        arguments = {
            name: self.resolve(hints[name])
            for name, parameter in signature.parameters.items()
            if parameter.default is inspect.Parameter.empty and name in hints
        }
        return interface(**arguments)


