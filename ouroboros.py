def parse_block():
    expect(T_LBRACE, "expected {")
    while tk() != T_RBRACE:
        if tk() == T_EOF:
            fail("unterminated block")
        parse_stmt()
    advance()
    return 0


def parse_stmt():
    if tk() == T_VAR:
        advance()
        if tk() != T_IDENT:
            fail("expected a name after var")
        start = tstart()
        length = tlen()
        advance()
        expect(T_ASSIGN, "expected = in var declaration")
        r = parse_expr()
        expect(T_SEMI, "expected ;")
        slot = declare_local(start, length)
        gen_store(r, gen_slot_addr(slot))
        return 0
    if tk() == T_IF:
        advance()
        expect(T_LPAREN, "expected ( after if")
        c = parse_expr()
        expect(T_RPAREN, "expected )")
        lthen = new_label()
        lelse = new_label()
        lend = new_label()
        emit_cond_br(c, lthen, lelse)
        emit_label(lthen)
        parse_block()
        emit_br(lend)
        emit_label(lelse)
        if tk() == T_ELSE:
            advance()
            parse_block()
        emit_br(lend)
        emit_label(lend)
        return 0
    if tk() == T_WHILE:
        advance()
        lhead = new_label()
        lbody = new_label()
        lend = new_label()
        emit_br(lhead)
        emit_label(lhead)
        expect(T_LPAREN, "expected ( after while")
        c = parse_expr()
        expect(T_RPAREN, "expected )")
        emit_cond_br(c, lbody, lend)
        emit_label(lbody)
        parse_block()
        emit_br(lhead)
        emit_label(lend)
        return 0
    if tk() == T_RETURN:
        advance()
        r = parse_expr()
        expect(T_SEMI, "expected ;")
        es("  ret i64 ")
        er(r)
        es("\n")
        emit_label(new_label())
        return 0
    if tk() == T_MEM:
        advance()
        expect(T_LBRACK, "expected [ after mem")
        i = parse_expr()
        expect(T_RBRACK, "expected ]")
        expect(T_ASSIGN, "expected = in mem assignment")
        v = parse_expr()
        expect(T_SEMI, "expected ;")
        gen_store(v, gen_mem_addr(i))
        return 0
    if tk() == T_IDENT and tk2() == T_ASSIGN:
        start = tstart()
        length = tlen()
        advance()
        advance()
        r = parse_expr()
        expect(T_SEMI, "expected ;")
        slot = find_local(start, length)
        if slot >= 0:
            gen_store(r, gen_slot_addr(slot))
            return 0
        if find_global(start, length) >= 0:
            gen_global_store(r, start, length)
            return 0
        fail("assignment to unknown identifier")
    parse_expr()
    expect(T_SEMI, "expected ;")
    return 0


