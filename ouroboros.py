class TokenKind(enum.Enum):
    IDENTIFIER = enum.auto()
    INTEGER = enum.auto()
    PLUS = enum.auto()
    MINUS = enum.auto()
    ASSIGN = enum.auto()
    TERMINATOR = enum.auto()
    ELLIPSIS = enum.auto()
    END_OF_STREAM = enum.auto()


class TransducerState(enum.Enum):
    AWAITING_LEXEME = enum.auto()
    ACCUMULATING_IDENTIFIER = enum.auto()
    ACCUMULATING_INTEGER = enum.auto()
    DISCARDING_COMMENT = enum.auto()


@dataclass(frozen=True, slots=True)
class SourcePosition:
    line: int
    column: int

    def __str__(self) -> str:
        return f"{self.line}:{self.column}"


@dataclass(frozen=True, slots=True)
class Token:
    kind: TokenKind
    lexeme: str
    position: SourcePosition

    def expect(self, kind: TokenKind, lexeme: str | None = None) -> "Token":
        if self.kind is not kind or (lexeme is not None and self.lexeme != lexeme):
            raise SyntaxError_(
                f"{self.position}: expected {lexeme or kind.name}, found {self.lexeme!r}"
            )
        return self


_PUNCTUATION_ALPHABET: Final[Mapping[str, TokenKind]] = {
    "+": TokenKind.PLUS,
    "-": TokenKind.MINUS,
    "=": TokenKind.ASSIGN,
    ";": TokenKind.TERMINATOR,
}


class FiniteStateTransducer:
    """Deterministic character-driven tokenizer for GSL source text."""

    def __init__(self, source: str) -> None:
        self._source = source
        self._state = TransducerState.AWAITING_LEXEME

    @instrumented
    def tokenize(self) -> tuple[Token, ...]:
        emitted: list[Token] = []
        buffer: list[str] = []
        anchor = SourcePosition(1, 1)
        line, column = 1, 1
        index = 0
        source = self._source + "\n"

        while index < len(source):
            character = source[index]
            here = SourcePosition(line, column)

            match self._state:
                case TransducerState.DISCARDING_COMMENT:
                    if character == "\n":
                        self._state = TransducerState.AWAITING_LEXEME

                case TransducerState.ACCUMULATING_IDENTIFIER:
                    if character.isalnum() or character == "_":
                        buffer.append(character)
                    else:
                        emitted.append(
                            Token(TokenKind.IDENTIFIER, "".join(buffer), anchor)
                        )
                        buffer.clear()
                        self._state = TransducerState.AWAITING_LEXEME
                        continue

                case TransducerState.ACCUMULATING_INTEGER:
                    if character.isdigit():
                        buffer.append(character)
                    else:
                        emitted.append(
                            Token(TokenKind.INTEGER, "".join(buffer), anchor)
                        )
                        buffer.clear()
                        self._state = TransducerState.AWAITING_LEXEME
                        continue

                case TransducerState.AWAITING_LEXEME:
                    if character == "#":
                        self._state = TransducerState.DISCARDING_COMMENT
                    elif character.isspace():
                        pass
                    elif character.isalpha() or character == "_":
                        anchor = here
                        buffer.append(character)
                        self._state = TransducerState.ACCUMULATING_IDENTIFIER
                    elif character.isdigit():
                        anchor = here
                        buffer.append(character)
                        self._state = TransducerState.ACCUMULATING_INTEGER
                    elif character == ".":
                        if source[index : index + 2] != "..":
                            raise LexicalError(f"{here}: solitary '.' is not a lexeme")
                        emitted.append(Token(TokenKind.ELLIPSIS, "..", here))
                        index += 1
                        column += 1
                    elif character in _PUNCTUATION_ALPHABET:
                        emitted.append(
                            Token(_PUNCTUATION_ALPHABET[character], character, here)
                        )
                    else:
                        raise LexicalError(f"{here}: unexpected character {character!r}")

            if character == "\n":
                line, column = line + 1, 1
            else:
                column += 1
            index += 1

        emitted.append(
            Token(TokenKind.END_OF_STREAM, "<eof>", SourcePosition(line, column))
        )
        return tuple(emitted)


