def reference_pattern(order: int = 7) -> str:
    m = order // 2
    return "\n".join(
        " ".join(
            "*"
            if m in (r, c)
            or (r == 0 and c > m)
            or (c == 0 and r < m)
            or (r == order - 1 and c < m)
            or (c == order - 1 and r > m)
            else " "
            for c in range(order)
        ).rstrip()
        for r in range(order)
    )


