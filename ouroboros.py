class Coordinate:
    """Interned, immutable ordinate pair in row-major lattice space (flyweight)."""

    __slots__ = ("row", "column", "__weakref__")
    __match_args__ = ("row", "column")

    _pool: ClassVar[MutableMapping[tuple[int, int], "Coordinate"]] = (
        weakref.WeakValueDictionary()
    )

    def __new__(cls, row: int, column: int) -> "Coordinate":
        key = (row, column)
        interned = cls._pool.get(key)
        if interned is not None:
            return interned
        instance = super().__new__(cls)
        object.__setattr__(instance, "row", row)
        object.__setattr__(instance, "column", column)
        cls._pool[key] = instance
        return instance

    def __setattr__(self, name: str, value: Any) -> None:
        raise AttributeError(f"{type(self).__name__} is immutable")

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, Coordinate):
            return NotImplemented
        return self.row == other.row and self.column == other.column

    def __hash__(self) -> int:
        return hash((self.row, self.column))

    def __lt__(self, other: "Coordinate") -> bool:
        return (self.row, self.column) < (other.row, other.column)

    def __repr__(self) -> str:
        return f"Coordinate({self.row}, {self.column})"

    def translated(self, delta: "Coordinate") -> "Coordinate":
        return Coordinate(self.row + delta.row, self.column + delta.column)

    def negated(self) -> "Coordinate":
        return Coordinate(-self.row, -self.column)


@dataclass(frozen=True, slots=True)
class LinearOperator:
    """A 2x2 endomorphism of the integer plane, in row-major component order."""

    a: int
    b: int
    c: int
    d: int

    IDENTITY: ClassVar["LinearOperator"]

    def __matmul__(self, other: "LinearOperator") -> "LinearOperator":
        return LinearOperator(
            self.a * other.a + self.b * other.c,
            self.a * other.b + self.b * other.d,
            self.c * other.a + self.d * other.c,
            self.c * other.b + self.d * other.d,
        )

    def __call__(self, vector: Coordinate) -> Coordinate:
        return Coordinate(
            self.a * vector.row + self.b * vector.column,
            self.c * vector.row + self.d * vector.column,
        )

    @property
    def determinant(self) -> int:
        return self.a * self.d - self.b * self.c

    def conjugated_about(
        self, pivot: Coordinate
    ) -> Callable[[Coordinate], Coordinate]:
        def _affine(point: Coordinate) -> Coordinate:
            return self(point.translated(pivot.negated())).translated(pivot)

        return _affine


LinearOperator.IDENTITY = LinearOperator(1, 0, 0, 1)

QUARTER_TURN_GENERATOR: Final[LinearOperator] = LinearOperator(0, 1, -1, 0)


@dataclass(frozen=True, slots=True)
class RotationGroup:
    """A finite operator group obtained by closure of a generator set."""

    pivot: Coordinate
    elements: tuple[LinearOperator, ...]

    @classmethod
    @instrumented
    def generated_by(
        cls,
        generator: LinearOperator,
        pivot: Coordinate,
        expected_order: int = QUARTER_TURN_CARDINALITY,
    ) -> "RotationGroup":
        accumulated: list[LinearOperator] = [LinearOperator.IDENTITY]
        seen = {LinearOperator.IDENTITY}
        frontier = LinearOperator.IDENTITY
        for _ in range(expected_order * expected_order):
            frontier = frontier @ generator
            if frontier in seen:
                break
            seen.add(frontier)
            accumulated.append(frontier)
        instance = cls(pivot=pivot, elements=tuple(accumulated))
        instance._verify_axioms(expected_order)
        return instance

    def _verify_axioms(self, expected_order: int) -> None:
        if len(self.elements) != expected_order:
            raise GroupAxiomViolation(
                f"generated group has order {len(self.elements)}, "
                f"expected {expected_order}"
            )
        if LinearOperator.IDENTITY not in self.elements:
            raise GroupAxiomViolation("generated set lacks a neutral element")
        population = set(self.elements)
        for left, right in itertools.product(self.elements, repeat=2):
            if left @ right not in population:
                raise GroupAxiomViolation(f"closure violated by {left!r} @ {right!r}")
        for element in self.elements:
            if not any(
                element @ candidate == LinearOperator.IDENTITY
                for candidate in self.elements
            ):
                raise GroupAxiomViolation(f"{element!r} has no inverse in the group")
        for x, y, z in itertools.product(self.elements, repeat=3):
            if (x @ y) @ z != x @ (y @ z):
                raise GroupAxiomViolation("associativity violated")
        _LOGGER.debug("group axioms verified for order %d", expected_order)

    def orbit(self, seed: Coordinate) -> Iterator[Coordinate]:
        return (
            element.conjugated_about(self.pivot)(seed) for element in self.elements
        )

    def close(self, support: Iterable[Coordinate]) -> FrozenSet[Coordinate]:
        return frozenset(
            itertools.chain.from_iterable(self.orbit(point) for point in support)
        )

    def is_invariant(self, support: FrozenSet[Coordinate]) -> bool:
        return all(self.close({point}) <= support for point in support)


