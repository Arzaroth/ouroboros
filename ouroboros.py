class BytecodeEmitter(AstVisitor[None]):
    """Lowers a validated syntax tree into linear GVM object code."""

    def __init__(self, model: SemanticModel) -> None:
        self._model = model
        self._buffer: list[Instruction] = []

    @instrumented
    def lower(self, program: Program) -> ObjectModule:
        program.accept(self)
        self._buffer.append(CloseUnderGroup())
        self._buffer.append(Halt())
        if not any(isinstance(item, EmitOrientedRun) for item in self._buffer):
            raise CodeGenerationError("lowering produced no emission instructions")
        return ObjectModule(
            instructions=tuple(self._buffer),
            order=self._model.order,
            symmetry_cardinality=self._model.symmetry_cardinality,
        )

    def visit_program(self, node: Program) -> None:
        for declaration in node.declarations:
            declaration.accept(self)

    def visit_lattice_declaration(self, node: LatticeDeclaration) -> None:
        return None

    def visit_symmetry_declaration(self, node: SymmetryDeclaration) -> None:
        return None

    def visit_stroke_declaration(self, node: StrokeDeclaration) -> None:
        return None

    def visit_emit_statement(self, node: EmitStatement) -> None:
        stroke = self._model.strokes[node.name]
        stroke.index.accept(self)
        stroke.span.accept(self)
        self._buffer.append(EmitOrientedRun(stroke.orientation))

    def visit_integer_literal(self, node: IntegerLiteral) -> None:
        self._buffer.append(PushConstant(node.value))

    def visit_symbol_reference(self, node: SymbolReference) -> None:
        self._buffer.append(LoadIntrinsic(node.name))

    def visit_binary_operation(self, node: BinaryOperation) -> None:
        node.left.accept(self)
        node.right.accept(self)
        self._buffer.append(
            BinaryAdd() if node.operator_token is TokenKind.PLUS else BinarySubtract()
        )

    def visit_span(self, node: Span) -> None:
        node.lower.accept(self)
        node.upper.accept(self)
        self._buffer.append(MakeInterval())


