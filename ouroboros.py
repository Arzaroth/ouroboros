class AstVisitor(Generic[_T], abc.ABC):
    """Double-dispatch visitor over the GSL abstract syntax tree."""

    @abc.abstractmethod
    def visit_program(self, node: "Program") -> _T: ...

    @abc.abstractmethod
    def visit_lattice_declaration(self, node: "LatticeDeclaration") -> _T: ...

    @abc.abstractmethod
    def visit_symmetry_declaration(self, node: "SymmetryDeclaration") -> _T: ...

    @abc.abstractmethod
    def visit_stroke_declaration(self, node: "StrokeDeclaration") -> _T: ...

    @abc.abstractmethod
    def visit_emit_statement(self, node: "EmitStatement") -> _T: ...

    @abc.abstractmethod
    def visit_integer_literal(self, node: "IntegerLiteral") -> _T: ...

    @abc.abstractmethod
    def visit_symbol_reference(self, node: "SymbolReference") -> _T: ...

    @abc.abstractmethod
    def visit_binary_operation(self, node: "BinaryOperation") -> _T: ...

    @abc.abstractmethod
    def visit_span(self, node: "Span") -> _T: ...


class AstNode(abc.ABC):
    __slots__ = ()

    @abc.abstractmethod
    def accept(self, visitor: AstVisitor[_T]) -> _T: ...

    def children(self) -> Iterator["AstNode"]:
        for value in (getattr(self, slot, None) for slot in self._slot_names()):
            if isinstance(value, AstNode):
                yield value
            elif isinstance(value, tuple):
                yield from (item for item in value if isinstance(item, AstNode))

    @classmethod
    def _slot_names(cls) -> tuple[str, ...]:
        return tuple(
            itertools.chain.from_iterable(
                getattr(base, "__slots__", ()) for base in cls.__mro__
            )
        )


