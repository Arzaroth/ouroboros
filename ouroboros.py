def parse_call_builtin(kind, first_arg):
    if kind == 1:
        t = new_reg()
        es("  ")
        er(t)
        es(" = trunc i64 ")
        er(first_arg)
        es(" to i32\n")
        u = new_reg()
        es("  ")
        er(u)
        es(" = call i32 @putchar(i32 ")
        er(t)
        es(")\n")
        r = new_reg()
        es("  ")
        er(r)
        es(" = sext i32 ")
        er(u)
        es(" to i64\n")
        return r
    if kind == 2:
        u = new_reg()
        es("  ")
        er(u)
        es(" = call i32 @getchar()\n")
        r = new_reg()
        es("  ")
        er(r)
        es(" = sext i32 ")
        er(u)
        es(" to i64\n")
        return r
    t = new_reg()
    es("  ")
    er(t)
    es(" = trunc i64 ")
    er(first_arg)
    es(" to i32\n")
    es("  call void @exit(i32 ")
    er(t)
    es(")\n")
    return gen_const(0)


def parse_primary():
    if tk() == T_NUM:
        v = tnum()
        advance()
        return gen_const(v)
    if tk() == T_STR:
        v = tnum()
        advance()
        return gen_const(v)
    if tk() == T_LPAREN:
        advance()
        r = parse_expr()
        expect(T_RPAREN, "expected )")
        return r
    if tk() == T_MEM:
        advance()
        expect(T_LBRACK, "expected [ after mem")
        i = parse_expr()
        expect(T_RBRACK, "expected ]")
        return gen_load(gen_mem_addr(i))
    if tk() == T_IDENT:
        start = tstart()
        length = tlen()
        advance()
        if tk() != T_LPAREN:
            slot = find_local(start, length)
            if slot >= 0:
                return gen_load(gen_slot_addr(slot))
            if find_global(start, length) >= 0:
                return gen_global_load(start, length)
            fail("unknown identifier")
        advance()
        if kw_is(start, length, "putchar"):
            a = parse_expr()
            expect(T_RPAREN, "expected )")
            return parse_call_builtin(1, a)
        if kw_is(start, length, "getchar"):
            expect(T_RPAREN, "expected )")
            return parse_call_builtin(2, 0)
        if kw_is(start, length, "exit"):
            a = parse_expr()
            expect(T_RPAREN, "expected )")
            return parse_call_builtin(3, a)
        nargs = 0
        while tk() != T_RPAREN:
            if nargs > 0:
                expect(T_COMMA, "expected , between arguments")
            mem[TOKBUF + 100 + nargs] = parse_expr()
            nargs = nargs + 1
            if nargs > 8:
                fail("too many arguments")
        advance()
        r = new_reg()
        es("  ")
        er(r)
        es(" = call i64 @f_")
        emit_name(start, length)
        es("(")
        i = 0
        while i < nargs:
            if i > 0:
                es(", ")
            es("i64 ")
            er(mem[TOKBUF + 100 + i])
            i = i + 1
        es(")\n")
        return r
    fail("expected an expression")
    return 0


def parse_unary():
    if tk() == T_MINUS:
        advance()
        a = parse_unary()
        return gen_binary(T_MINUS, gen_const(0), a)
    if tk() == T_NOT:
        advance()
        a = parse_unary()
        return gen_compare(T_EQ, a, gen_const(0))
    return parse_primary()


def parse_mul():
    a = parse_unary()
    while tk() == T_STAR or tk() == T_SLASH or tk() == T_PERCENT:
        op = tk()
        advance()
        b = parse_unary()
        a = gen_binary(op, a, b)
    return a


def parse_add():
    a = parse_mul()
    while tk() == T_PLUS or tk() == T_MINUS:
        op = tk()
        advance()
        b = parse_mul()
        a = gen_binary(op, a, b)
    return a


def parse_rel():
    a = parse_add()
    while tk() == T_LT or tk() == T_LE or tk() == T_GT or tk() == T_GE:
        op = tk()
        advance()
        b = parse_add()
        a = gen_compare(op, a, b)
    return a


def parse_eq():
    a = parse_rel()
    while tk() == T_EQ or tk() == T_NE:
        op = tk()
        advance()
        b = parse_rel()
        a = gen_compare(op, a, b)
    return a


def parse_and():
    a = parse_eq()
    while tk() == T_ANDAND:
        advance()
        slot = alloc_temp_slot()
        s1 = gen_slot_addr(slot)
        es("  store i64 0, ptr ")
        er(s1)
        es(", align 8\n")
        lrhs = new_label()
        lend = new_label()
        emit_cond_br(a, lrhs, lend)
        emit_label(lrhs)
        b = parse_eq()
        v = gen_compare(T_NE, b, gen_const(0))
        gen_store(v, gen_slot_addr(slot))
        emit_br(lend)
        emit_label(lend)
        a = gen_load(gen_slot_addr(slot))
    return a


def parse_or():
    a = parse_and()
    while tk() == T_OROR:
        advance()
        slot = alloc_temp_slot()
        s1 = gen_slot_addr(slot)
        es("  store i64 1, ptr ")
        er(s1)
        es(", align 8\n")
        lrhs = new_label()
        lend = new_label()
        emit_cond_br(a, lend, lrhs)
        emit_label(lrhs)
        b = parse_and()
        v = gen_compare(T_NE, b, gen_const(0))
        gen_store(v, gen_slot_addr(slot))
        emit_br(lend)
        emit_label(lend)
        a = gen_load(gen_slot_addr(slot))
    return a


def parse_expr():
    return parse_or()


