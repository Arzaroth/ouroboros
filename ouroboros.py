@dataclass(frozen=True, slots=True)
class ConcurrentAsteriskRasterizer:
    """Materializes each scanline on a worker thread, then reassembles in order."""

    intercell_delimiter: str = " "
    interline_delimiter: str = "\n"

    def _scanline(self, context: RenderContext, row: int) -> str:
        return self.intercell_delimiter.join(
            str(
                Ink.OCCUPIED
                if Coordinate(row, column) in context.support
                else Ink.VACANT
            )
            for column in range(context.order)
        ).rstrip()

    def rasterize(self, context: RenderContext) -> str:
        workers = min(RASTERIZATION_PARALLELISM_CEILING, max(1, context.order))
        with ThreadPoolExecutor(max_workers=workers) as pool:
            scanlines = pool.map(
                functools.partial(self._scanline, context), range(context.order)
            )
            return self.interline_delimiter.join(scanlines)


