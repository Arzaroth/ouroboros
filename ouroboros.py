def new_reg():
    global regcnt
    regcnt = regcnt + 1
    return regcnt


def new_label():
    global labelcnt
    labelcnt = labelcnt + 1
    return labelcnt


def er(r):
    es("%t")
    en(r)
    return 0


def elabel(l):
    es("L")
    en(l)
    return 0


def emit_label(l):
    elabel(l)
    es(":\n")
    return 0


def emit_br(l):
    es("  br label %")
    elabel(l)
    es("\n")
    return 0


def emit_cond_br(r, a, b):
    t = new_reg()
    es("  ")
    er(t)
    es(" = icmp ne i64 ")
    er(r)
    es(", 0\n")
    es("  br i1 ")
    er(t)
    es(", label %")
    elabel(a)
    es(", label %")
    elabel(b)
    es("\n")
    return 0


def gen_const(v):
    r = new_reg()
    es("  ")
    er(r)
    es(" = add i64 0, ")
    en(v)
    es("\n")
    return r


def gen_slot_addr(slot):
    r = new_reg()
    es("  ")
    er(r)
    es(" = getelementptr inbounds [")
    en(FRAME)
    es(" x i64], ptr %frame, i64 0, i64 ")
    en(slot)
    es("\n")
    return r


def gen_mem_addr(index_reg):
    r = new_reg()
    es("  ")
    er(r)
    es(" = getelementptr inbounds [")
    en(MEMSIZE)
    es(" x i64], ptr @memory, i64 0, i64 ")
    er(index_reg)
    es("\n")
    return r


def gen_load(addr_reg):
    r = new_reg()
    es("  ")
    er(r)
    es(" = load i64, ptr ")
    er(addr_reg)
    es(", align 8\n")
    return r


def gen_store(value_reg, addr_reg):
    es("  store i64 ")
    er(value_reg)
    es(", ptr ")
    er(addr_reg)
    es(", align 8\n")
    return 0


def gen_global_load(start, length):
    r = new_reg()
    es("  ")
    er(r)
    es(" = load i64, ptr @g_")
    emit_name(start, length)
    es(", align 8\n")
    return r


def gen_global_store(value_reg, start, length):
    es("  store i64 ")
    er(value_reg)
    es(", ptr @g_")
    emit_name(start, length)
    es(", align 8\n")
    return 0


def gen_binary(op, a, b):
    r = new_reg()
    es("  ")
    er(r)
    if op == T_PLUS:
        es(" = add nsw i64 ")
    if op == T_MINUS:
        es(" = sub nsw i64 ")
    if op == T_STAR:
        es(" = mul nsw i64 ")
    if op == T_SLASH:
        es(" = sdiv i64 ")
    if op == T_PERCENT:
        es(" = srem i64 ")
    er(a)
    es(", ")
    er(b)
    es("\n")
    return r


def gen_compare(op, a, b):
    c = new_reg()
    es("  ")
    er(c)
    if op == T_EQ:
        es(" = icmp eq i64 ")
    if op == T_NE:
        es(" = icmp ne i64 ")
    if op == T_LT:
        es(" = icmp slt i64 ")
    if op == T_LE:
        es(" = icmp sle i64 ")
    if op == T_GT:
        es(" = icmp sgt i64 ")
    if op == T_GE:
        es(" = icmp sge i64 ")
    er(a)
    es(", ")
    er(b)
    es("\n")
    r = new_reg()
    es("  ")
    er(r)
    es(" = zext i1 ")
    er(c)
    es(" to i64\n")
    return r


