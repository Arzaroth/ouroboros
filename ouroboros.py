class Result(Generic[_T], abc.ABC):
    """Discriminated union modelling a computation that may have failed."""

    __slots__ = ()

    @abc.abstractmethod
    def map(self, morphism: Callable[[_T], _U]) -> "Result[_U]": ...

    @abc.abstractmethod
    def and_then(self, arrow: Callable[[_T], "Result[_U]"]) -> "Result[_U]": ...

    @abc.abstractmethod
    def unwrap_or_raise(self) -> _T: ...

    @property
    @abc.abstractmethod
    def is_ok(self) -> bool: ...

    @staticmethod
    def attempt(thunk: Callable[[], _T]) -> "Result[_T]":
        try:
            return Ok(thunk())
        except GlyphPlatformError as exc:
            return Err(exc)


@dataclass(frozen=True, slots=True)
class Ok(Result[_T]):
    """The successful inhabitant of :class:`Result`."""

    value: _T

    def map(self, morphism: Callable[[_T], _U]) -> Result[_U]:
        return Result.attempt(lambda: morphism(self.value))

    def and_then(self, arrow: Callable[[_T], Result[_U]]) -> Result[_U]:
        return arrow(self.value)

    def unwrap_or_raise(self) -> _T:
        return self.value

    @property
    def is_ok(self) -> bool:
        return True


@dataclass(frozen=True, slots=True)
class Err(Result[_T]):
    """The failed inhabitant of :class:`Result`."""

    failure: GlyphPlatformError

    def map(self, morphism: Callable[[_T], _U]) -> Result[_U]:
        return Err(self.failure)

    def and_then(self, arrow: Callable[[_T], Result[_U]]) -> Result[_U]:
        return Err(self.failure)

    def unwrap_or_raise(self) -> _T:
        raise self.failure

    @property
    def is_ok(self) -> bool:
        return False


def instrumented(callable_: Callable[..., _T]) -> Callable[..., _T]:
    """Decorator emitting structured entry and exit telemetry."""

    @functools.wraps(callable_)
    def _wrapper(*args: Any, **kwargs: Any) -> _T:
        started = time.perf_counter()
        _LOGGER.debug("enter %s", callable_.__qualname__)
        try:
            return callable_(*args, **kwargs)
        finally:
            _LOGGER.debug(
                "exit  %s (%.6fs)", callable_.__qualname__, time.perf_counter() - started
            )

    return _wrapper


