@dataclass(frozen=True, slots=True)
class EmissionCommand:
    """Undoable mutation of the canvas support set (command pattern)."""

    cells: FrozenSet[Coordinate]

    def apply(self, canvas: set[Coordinate]) -> None:
        canvas |= self.cells

    def revert(self, canvas: set[Coordinate]) -> None:
        canvas -= self.cells


class EmissionJournal:
    """Append-only journal granting transactional rollback over emissions."""

    def __init__(self) -> None:
        self._entries: list[EmissionCommand] = []

    def record(self, command: EmissionCommand, canvas: set[Coordinate]) -> None:
        command.apply(canvas)
        self._entries.append(command)

    def rollback(self, canvas: set[Coordinate]) -> None:
        while self._entries:
            self._entries.pop().revert(canvas)

    def __len__(self) -> int:
        return len(self._entries)


class GlyphVirtualMachine:
    """A stack machine executing GVM object code over a lattice canvas."""

    def __init__(self, module: ObjectModule) -> None:
        self._module = module
        self._stack: list[Any] = []
        self._canvas: set[Coordinate] = set()
        self._journal = EmissionJournal()
        self._program_counter = 0
        self._apothem = module.order // 2
        self._group = RotationGroup.generated_by(
            QUARTER_TURN_GENERATOR,
            Coordinate(self._apothem, self._apothem),
            module.symmetry_cardinality,
        )
        self._intrinsics: Mapping[str, int] = {
            "zero": 0,
            "apothem": self._apothem,
            "extremum": module.order - 1,
            "magnitude": module.order,
        }

    @contextmanager
    def _transaction(self) -> Iterator[None]:
        try:
            yield
        except Exception:
            self._journal.rollback(self._canvas)
            raise

    @instrumented
    def run(self) -> FrozenSet[Coordinate]:
        with self._transaction():
            while True:
                if self._program_counter >= len(self._module.instructions):
                    raise ExecutionFault("program counter ran off the end of the module")
                instruction = self._module.instructions[self._program_counter]
                self._program_counter += 1
                if isinstance(instruction, Halt):
                    break
                self._execute(instruction)
            if self._stack:
                raise ExecutionFault(f"operand stack not drained: {self._stack!r}")
        return frozenset(self._canvas)

    def _pop(self) -> Any:
        try:
            return self._stack.pop()
        except IndexError as exc:
            raise ExecutionFault("operand stack underflow") from exc

    @functools.singledispatchmethod
    def _execute(self, instruction: Instruction) -> None:
        raise ExecutionFault(f"illegal instruction {instruction!r}")

    @_execute.register(PushConstant)
    def _(self, instruction: PushConstant) -> None:
        self._stack.append(instruction.value)

    @_execute.register(LoadIntrinsic)
    def _(self, instruction: LoadIntrinsic) -> None:
        try:
            self._stack.append(self._intrinsics[instruction.name])
        except KeyError as exc:
            raise ExecutionFault(f"unbound intrinsic {instruction.name!r}") from exc

    @_execute.register(BinaryAdd)
    def _(self, instruction: BinaryAdd) -> None:
        right, left = self._pop(), self._pop()
        self._stack.append(operator.add(left, right))

    @_execute.register(BinarySubtract)
    def _(self, instruction: BinarySubtract) -> None:
        right, left = self._pop(), self._pop()
        self._stack.append(operator.sub(left, right))

    @_execute.register(MakeInterval)
    def _(self, instruction: MakeInterval) -> None:
        upper, lower = self._pop(), self._pop()
        if lower > upper:
            raise ExecutionFault(f"degenerate interval [{lower}, {upper}]")
        self._stack.append(range(lower, upper + 1))

    @_execute.register(EmitOrientedRun)
    def _(self, instruction: EmitOrientedRun) -> None:
        interval, index = self._pop(), self._pop()
        factory = (
            (lambda scalar: Coordinate(index, scalar))
            if instruction.orientation is Orientation.ROW
            else (lambda scalar: Coordinate(scalar, index))
        )
        self._journal.record(
            EmissionCommand(frozenset(map(factory, interval))), self._canvas
        )

    @_execute.register(CloseUnderGroup)
    def _(self, instruction: CloseUnderGroup) -> None:
        closure = self._group.close(self._canvas)
        self._journal.record(EmissionCommand(closure), self._canvas)

    @property
    def group(self) -> RotationGroup:
        return self._group


