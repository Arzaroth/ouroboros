class RecursiveDescentParser:
    """LL(1) recursive-descent parser with precedence climbing for arithmetic."""

    def __init__(self, tokens: Sequence[Token]) -> None:
        self._tokens = tokens
        self._cursor = 0

    def _peek(self, offset: int = 0) -> Token:
        return self._tokens[min(self._cursor + offset, len(self._tokens) - 1)]

    def _advance(self) -> Token:
        token = self._peek()
        self._cursor += 1
        return token

    def _consume(self, kind: TokenKind, lexeme: str | None = None) -> Token:
        return self._advance().expect(kind, lexeme)

    def _at_keyword(self, lexeme: str) -> bool:
        token = self._peek()
        return token.kind is TokenKind.IDENTIFIER and token.lexeme == lexeme

    @instrumented
    def parse(self) -> Program:
        declarations: list[AstNode] = []
        while self._peek().kind is not TokenKind.END_OF_STREAM:
            declarations.append(self._parse_declaration())
        return Program(tuple(declarations))

    def _parse_declaration(self) -> AstNode:
        head = self._peek()
        match head.lexeme:
            case "lattice":
                node = self._parse_lattice()
            case "symmetry":
                node = self._parse_symmetry()
            case "stroke":
                node = self._parse_stroke()
            case "emit":
                node = self._parse_emit()
            case _:
                raise SyntaxError_(
                    f"{head.position}: unknown declaration head {head.lexeme!r}"
                )
        self._consume(TokenKind.TERMINATOR)
        return node

    def _parse_lattice(self) -> LatticeDeclaration:
        self._consume(TokenKind.IDENTIFIER, "lattice")
        self._consume(TokenKind.IDENTIFIER, "order")
        return LatticeDeclaration(int(self._consume(TokenKind.INTEGER).lexeme))

    def _parse_symmetry(self) -> SymmetryDeclaration:
        self._consume(TokenKind.IDENTIFIER, "symmetry")
        self._consume(TokenKind.IDENTIFIER, "cyclic")
        cardinality = int(self._consume(TokenKind.INTEGER).lexeme)
        self._consume(TokenKind.IDENTIFIER, "about")
        return SymmetryDeclaration(cardinality, self._consume(TokenKind.IDENTIFIER).lexeme)

    def _parse_stroke(self) -> StrokeDeclaration:
        self._consume(TokenKind.IDENTIFIER, "stroke")
        name = self._consume(TokenKind.IDENTIFIER).lexeme
        self._consume(TokenKind.ASSIGN)
        orientation_token = self._consume(TokenKind.IDENTIFIER)
        try:
            orientation = Orientation(orientation_token.lexeme)
        except ValueError as exc:
            raise SyntaxError_(
                f"{orientation_token.position}: {orientation_token.lexeme!r} "
                f"is not an orientation"
            ) from exc
        self._consume(TokenKind.IDENTIFIER, "at")
        index = self._parse_expression()
        self._consume(TokenKind.IDENTIFIER, "span")
        lower = self._parse_expression()
        self._consume(TokenKind.ELLIPSIS)
        upper = self._parse_expression()
        return StrokeDeclaration(name, orientation, index, Span(lower, upper))

    def _parse_emit(self) -> EmitStatement:
        self._consume(TokenKind.IDENTIFIER, "emit")
        return EmitStatement(self._consume(TokenKind.IDENTIFIER).lexeme)

    def _parse_expression(self) -> AstNode:
        node = self._parse_atom()
        while self._peek().kind in (TokenKind.PLUS, TokenKind.MINUS):
            operator_token = self._advance().kind
            node = BinaryOperation(operator_token, node, self._parse_atom())
        return node

    def _parse_atom(self) -> AstNode:
        token = self._advance()
        match token.kind:
            case TokenKind.INTEGER:
                return IntegerLiteral(int(token.lexeme))
            case TokenKind.IDENTIFIER:
                return SymbolReference(token.lexeme)
            case _:
                raise SyntaxError_(f"{token.position}: expected an atom, got {token.lexeme!r}")


