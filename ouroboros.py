class LexicalScope:
    """A chained symbol table supporting shadowing and parent delegation."""

    def __init__(self, parent: "LexicalScope | None" = None) -> None:
        self._parent = parent
        self._bindings: dict[str, Any] = {}

    def declare(self, name: str, payload: Any) -> None:
        if name in self._bindings:
            raise SemanticError(f"symbol {name!r} redeclared in the same scope")
        self._bindings[name] = payload

    def lookup(self, name: str) -> Any:
        scope: LexicalScope | None = self
        while scope is not None:
            if name in scope._bindings:
                return scope._bindings[name]
            scope = scope._parent
        raise SemanticError(f"unresolved symbol {name!r}")

    def descend(self) -> "LexicalScope":
        return LexicalScope(self)


@dataclass(slots=True)
class SemanticModel:
    """The analysis product handed to the lowering phase."""

    order: int = DEFAULT_LATTICE_ORDER
    symmetry_cardinality: int = QUARTER_TURN_CARDINALITY
    pivot: str = "centroid"
    strokes: dict[str, StrokeDeclaration] = field(default_factory=dict)
    emissions: list[str] = field(default_factory=list)


class SemanticAnalyzer(AstVisitor[None]):
    """Validates scoping, arity, parity and reachability across the tree."""

    def __init__(self) -> None:
        self.model = SemanticModel()
        self._scope = LexicalScope()
        for intrinsic in sorted(INTRINSIC_SYMBOLS):
            self._scope.declare(intrinsic, "intrinsic")

    @instrumented
    def analyze(self, program: Program) -> SemanticModel:
        program.accept(self)
        if not self.model.emissions:
            raise SemanticError("program emits no strokes; glyph would be vacuous")
        return self.model

    def visit_program(self, node: Program) -> None:
        for declaration in node.declarations:
            declaration.accept(self)

    def visit_lattice_declaration(self, node: LatticeDeclaration) -> None:
        if node.order < 3 or node.order % 2 == 0:
            raise SemanticError(
                f"lattice order must be an odd integer >= 3, received {node.order}"
            )
        self.model.order = node.order

    def visit_symmetry_declaration(self, node: SymmetryDeclaration) -> None:
        if node.pivot != "centroid":
            raise SemanticError(f"unsupported symmetry pivot {node.pivot!r}")
        if node.cardinality < 1:
            raise SemanticError("symmetry cardinality must be positive")
        self.model.symmetry_cardinality = node.cardinality
        self.model.pivot = node.pivot

    def visit_stroke_declaration(self, node: StrokeDeclaration) -> None:
        self._scope.declare(node.name, node)
        inner = self._scope.descend()
        previous, self._scope = self._scope, inner
        try:
            node.index.accept(self)
            node.span.accept(self)
        finally:
            self._scope = previous
        self.model.strokes[node.name] = node

    def visit_emit_statement(self, node: EmitStatement) -> None:
        binding = self._scope.lookup(node.name)
        if not isinstance(binding, StrokeDeclaration):
            raise SemanticError(f"{node.name!r} is not emittable")
        self.model.emissions.append(node.name)

    def visit_integer_literal(self, node: IntegerLiteral) -> None:
        return None

    def visit_symbol_reference(self, node: SymbolReference) -> None:
        if node.name not in INTRINSIC_SYMBOLS:
            raise SemanticError(f"{node.name!r} is not an intrinsic lattice symbol")

    def visit_binary_operation(self, node: BinaryOperation) -> None:
        node.left.accept(self)
        node.right.accept(self)

    def visit_span(self, node: Span) -> None:
        node.lower.accept(self)
        node.upper.accept(self)


