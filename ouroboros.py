class Instruction(abc.ABC):
    """Base of the Glyph Virtual Machine instruction set architecture."""

    _opcode_table: ClassVar[dict[str, int]] = {}
    opcode: ClassVar[int]

    def __init_subclass__(cls, **kwargs: Any) -> None:
        super().__init_subclass__(**kwargs)
        cls.opcode = len(Instruction._opcode_table)
        Instruction._opcode_table[cls.__name__] = cls.opcode

    def disassemble(self) -> str:
        operands = " ".join(
            f"{key}={value!r}" for key, value in vars(self).items()
        )
        return f"{self.opcode:>3}  {type(self).__name__:<20} {operands}"


